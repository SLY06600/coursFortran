program variables_demo
    ! Déclaration des variables
    integer :: age
    real :: taille
    character(len=20) :: nom

    ! Affectation des valeurs
    age = 25
    taille = 1.75
    nom = "Baraduc"

    ! Affichage
    print *, "Nom :", nom
    print *, "Age :", age
    print *, "Taille :", taille, "m"
end program variables_demo
